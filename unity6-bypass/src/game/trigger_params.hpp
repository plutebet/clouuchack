#pragma once
// ---------------------------------------------------------------------------
// trigger_params.hpp — все числовые параметры триггера, карты и памяти в одном
// месте. Значения помечены тем, откуда они взяты:
//   [ЛОГ]   — выведено из сессии /data/local/tmp/bycmd-debug/20261121-011618
//   [ДАМП]  — взято из dump.cs / профиля v100 и подтверждено логом
//   [ЗАПАС] — ресурсный/страховочный лимит, не влияет на логику
//
// ВАЖНО: офсеты памяти в этой сессии НЕ меняются. Лог доказывает, что они
// верные: libunity build-id совпал (match=1), HP читается (hp=100/78/51/24 max=100),
// 19 костей собираются (count=19 head=1), камера нативная (cam=1), szi и
// PlayerAnimationData читаются (visible/mow/bone_fresh в каждой VISCHECK).
// Менять офсеты по этому логу нельзя — сломается то, что работает. Проблема
// была не в офсетах, а в таймингах и в идентификации карты (см. map_world.hpp).
// ---------------------------------------------------------------------------

#include <cstdint>

namespace trigger_params {

// ===========================================================================
// 1. Профиль памяти (проверен этим логом, менять не нужно)
// ===========================================================================
// libunity.so build-id : 69815f2befe135c2   [ЛОГ] match=1
// игра                 : Standoff 2 1.1.0, Unity 6000.3.13f1
//                        versionCode 203982 на устройстве, 103982 в apk-манифесте
//                        (тот же libunity, набор .pkm подходит)
// szi (видимость)      : 6 байт с +0x10  [ДАМП] fhzz/mow/lixl/ojje/rjux/ukgq
// animation IsVisible   : presentation_animation_data -> animation_is_visible (1 байт)
// слой коллайдеров     : 14 = пули, 15 = ?, 0 = декор/скайбокс  [ЛОГ+АСЕТЫ]
//                        проверено офлайн по assets/maps: у Polygon 5561 из 6125
//                        треугольников лежат на 14, остальные 564 — на 0
//                        (материал 0xFFFFFFFF, это оболочка карты, не пол)
inline constexpr uint32_t kBulletLayer = 14;

// ===========================================================================
// 2. Тайминги выстрела
// ===========================================================================
// Задержка «курсор должен постоять на цели». 0 = жать сразу, как только луч
// попал в хит-бокс. Именно так и было в логе (fire #1 через 116 мс после
// появления цели), поэтому жалоба «сильная задержка» — не про эту настройку,
// а про blacklist ниже и про отказ стрелять при map=0.
inline constexpr int kDelayMs = 0;

// Сколько палец держит кнопку огня. 30 мс уже работало (63 подтверждённых
// попадания из 375 выстрелов), 35 — с запасом на 144 Гц экран.
inline constexpr int kHoldMs = 35;

// Дистанция до точки попадания вдоль луча. [ЛОГ] без лимита триггер стрелял
// на 40.1 м и 38.3 м — на телефоне это гарантированный промах сквозь полкарты.
inline constexpr float kMaxDistance = 30.f;
inline constexpr float kMinDistance = 0.f;

// ===========================================================================
// 3. Обратная связь по урону (главная причина «не стреляет»)
// ===========================================================================
// [ЛОГ] 312 из 375 выстрелов не дали урона, и по каждому сработал blacklist:
// 400 мс (144 шт), 2 с (104), 6 с (47), 15 с (17). 250 мс — слишком узкое окно
// для онлайна: на 120 Гц + пинг >60 мс урон приходит позже, и триггер считает
// честное попадание промахом, после чего молчит до 15 секунд.
inline constexpr long long kDamageWindowMs = 450;

// Сколько «подтверждён» считается правдой после реального урона.
inline constexpr long long kConfirmTtlMs = 1500;

// Лестница блокировки по серии «нет урона» (мс). Короче и мягче прежней:
// 400/2000/6000/15000 -> 300/1000/2500/5000.
inline constexpr long long kBlacklist[4] = {300, 1000, 2500, 5000};

// ===========================================================================
// 4. Идентификация карты: зонд «пол под ногами»
// ===========================================================================
// [ЛОГ] зонд проверял только 4 кандидата (attempts<4) и требовал попадания
// в пол на расстоянии 0.20..0.60 м от точки feet+0.40, то есть пол строго
// ±0.2 м от высоты ступней. В логе высота ступней встречается 0.00, 0.12,
// 0.28, 0.69 — при 0.28 зонд уже промахивался (0.40+0.28=0.68 > 0.60).
inline constexpr int   kMaxCandidates   = 23;    // пробовать все карты, не 4
inline constexpr float kCandidateMargin = 3.f;   // запас вокруг AABB карты
inline constexpr float kProbeUp         = 0.60f; // луч вниз начинается выше ступней
inline constexpr float kProbeDown       = 2.20f; // ...и уходит на 2.2 м вниз
// Допустимое превышение ступней над найденным полом: от -0.15 (стоим в
// геометрии/на ступеньке) до +0.90 (присед, прыжок, бег по рампе).
inline constexpr float kFloorMin = -0.15f;
inline constexpr float kFloorMax = 0.90f;

// Решение принимается по всем точкам (локальный игрок + враги), а не по
// одной пятой точке.
//
// ВАЖНО, что показывает офлайн-проверка на реальных .pkm и позициях из этого
// лога: AABB 23 карт сильно перекрываются, и у нескольких карт в центре есть
// ровная площадка около y=0. Поэтому одного кадра недостаточно: поддельная
// карта объясняет те же ступни не хуже настоящей (в окне сессии Pyramid
// совпадала 20/20 в одном матче, TrainingOutside 109/186 за всю сессию).
// Вывод: карту нужно подтверждать несколькими кадрами подряд, и требовать,
// чтобы она объясняла ВСЕ точки. Тогда плоская «чужая» площадка отваливается,
// как только игрок уходит на другой этаж или на рампу.
inline constexpr int  kConfirmVotes      = 2;     // сколько подряд удачных кадров
inline constexpr float kResidualMax      = 0.35f; // средний |feet-floor| для «объяснила всё»
inline constexpr int  kMinPointsToConfirm = 2;    // одна точка — не доказательство
inline constexpr long long kAmbiguityTimeoutMs = 15000; // сколько ждать разрешения неоднозначности

// Держать разобранные карты в памяти. [ЛОГ] за 20 минут было 892 полных
// разбора одних и тех же 4 карт — отсюда рывки и нагрев. С кэшем все 23
// карты разбираются один раз (~1.5 с на малом ядре, ~68 МБ) и дальше зонд
// это чистый raycast.
inline constexpr bool kCacheMaps = true;

// Сколько раз можно отбросить карту по «нет урона при чистом пути», прежде
// чем перестать её предлагать (иначе бесконечный цикл pick -> drop -> pick).
inline constexpr int kMaxDropsPerMap = 3;

// ===========================================================================
// 5. Логи
// ===========================================================================
inline constexpr int kRejectLogMs = 1000;   // не чаще раза в секунду
inline constexpr int kWallLogMs   = 1000;
inline constexpr int kStatusLogMs = 4000;

} // namespace trigger_params
